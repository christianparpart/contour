/// The environment variable that asks the `[encoding-pin]` tests to print their encodings.
inline constexpr auto UpdateFixturesVariable = std::string_view { "CONTOUR_UPDATE_FIXTURES" };

/// @param environment The environment to read UpdateFixturesVariable from.
/// @return Whether it asks for the encodings to be printed rather than compared.
[[nodiscard]] inline bool isFixtureUpdateRequested(core::Environment const& environment)
{
    return environment.get(UpdateFixturesVariable) == "1";
}

/// Spells @p bytes as a C++ array definition in the layout of this file, for pasting it in.
/// @param name The array's name.
/// @param bytes What it holds.
/// @return The definition, one line per sixteen bytes.
[[nodiscard]] inline std::string spelledFixture(std::string_view name, std::span<std::byte const> bytes)
{
    constexpr auto BytesPerLine = std::size_t { 16 };
    auto text = std::format("inline constexpr std::array<std::uint8_t, {}> {} {{", bytes.size(), name);
    for (auto const index: std::views::iota(std::size_t { 0 }, bytes.size()))
    {
        text += index % BytesPerLine == 0 ? "\n    " : " ";
        text += std::format("0x{:02x},", std::to_integer<unsigned>(bytes[index]));
    }
    text += "\n};\n";
    return text;
}

